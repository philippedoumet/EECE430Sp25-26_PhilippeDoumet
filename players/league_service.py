"""
Live league integration with TheSportsDB.

Our club competes in the Italian Volleyball League (SuperLega).
We pull real fixtures, scores and team data from TheSportsDB's free
public API and surface them to the coach portal.

The free key (3) supports:
    eventsround.php   — events for a given league round / season
    eventslast.php    — last event for a team
    search_all_teams  — list teams in a league
    lookupleague.php  — league metadata
"""
from __future__ import annotations

import datetime as _dt
import hashlib
import json
import time
from pathlib import Path

import requests
from django.conf import settings
from django.core.cache import cache


_BASE = "https://www.thesportsdb.com/api/v1/json"
_DEFAULT_TTL = 60 * 60 * 6   # 6 hours — caches stay warm for the whole demo
_THROTTLE_SECONDS = 0.25      # spread requests so we don't trigger the 429 limit
_SNAPSHOT_PATH = Path(__file__).resolve().parent / "league_snapshot.json"
_last_request_at = 0.0


def _api_url(path: str) -> str:
    return f"{_BASE}/{settings.LEAGUE_API_KEY}/{path}"


def _cache_key(path: str, params: dict | None) -> str:
    raw = f"{path}|{sorted((params or {}).items())}"
    digest = hashlib.md5(raw.encode("utf-8")).hexdigest()
    return f"league:{digest}"


def _throttle():
    global _last_request_at
    elapsed = time.monotonic() - _last_request_at
    if elapsed < _THROTTLE_SECONDS:
        time.sleep(_THROTTLE_SECONDS - elapsed)
    _last_request_at = time.monotonic()


def _get_json(path: str, params: dict | None = None, ttl: int = _DEFAULT_TTL) -> dict:
    cache_key = _cache_key(path, params)
    hit = cache.get(cache_key)
    if hit is not None:
        return hit

    _throttle()
    data: dict = {}
    try:
        resp = requests.get(
            _api_url(path),
            params=params or {},
            timeout=settings.LEAGUE_API_TIMEOUT,
        )
        if resp.status_code == 200:
            try:
                data = resp.json() or {}
            except ValueError:
                data = {}
    except requests.RequestException:
        data = {}

    # Only cache real responses. An empty / errored payload should not poison
    # the cache — let the next call retry the API.
    if data:
        cache.set(cache_key, data, ttl)
    return data


# ---------------------------------------------------------------------------
# Offline snapshot — used when the live API is unreachable / throttled.
# Generated by `python manage.py warm_league_cache --save-snapshot`.
# ---------------------------------------------------------------------------

def _load_snapshot() -> dict:
    if not _SNAPSHOT_PATH.exists():
        return {}
    try:
        return json.loads(_SNAPSHOT_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


